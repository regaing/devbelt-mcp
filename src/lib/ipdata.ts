/** IPv4 字符串转 32 位整数 */
export function ipToInt(ip: string): number {
  return ip.split(".").reduce((acc, o) => ((acc << 8) | parseInt(o, 10)) >>> 0, 0);
}

function cidrRange(cidr: string): [number, number] {
  if (cidr === "255.255.255.255") return [0xffffffff, 0xffffffff];
  const [ip, bitsStr] = cidr.split("/");
  const bits = parseInt(bitsStr, 10);
  const ipInt = ipToInt(ip);
  const mask = bits === 0 ? 0 : (~0 << (32 - bits)) >>> 0;
  // 注意：JS 位运算结果为有符号 32 位，需 >>> 0 转无符号后再比较
  return [(ipInt & mask) >>> 0, ((ipInt & mask) | (~mask >>> 0)) >>> 0];
}

export interface IpLookupResult {
  ip: string;
  type: string;
  region: string | null;
  isp: string | null;
  source: string;
  detail?: string;
}

/** 查询 IP 归属（内置精简段表，纯本地） */
export function ipLookup(ip: string): IpLookupResult {
  const int = ipToInt(ip);
  for (const [cidr, label] of SPECIAL_SEGMENTS) {
    const [lo, hi] = cidrRange(cidr);
    if (int >= lo && int <= hi) {
      return { ip, type: "特殊地址", region: null, isp: null, source: "RFC 标准定义", detail: label };
    }
  }
  for (const [cidr, region, isp] of CN_SEGMENTS) {
    const [lo, hi] = cidrRange(cidr);
    if (int >= lo && int <= hi) {
      return { ip, type: "公网地址", region, isp, source: "内置精简段表（代表性覆盖）" };
    }
  }
  return { ip, type: "公网地址", region: null, isp: null, source: "未收录（内置精简段表仅覆盖主要运营商段）" };
}
